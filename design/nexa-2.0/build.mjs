/* Build Nexa 2.0 prototype SVG source, contact sheets and Studio data. */
import fs from "node:fs";
import path from "node:path";
import icons from "./catalog.mjs";

const ROOT = path.resolve(import.meta.dirname, "../..");
const OUT = path.join(ROOT, "design/nexa-2.0");
const iconDir = path.join(OUT, "icons");
fs.mkdirSync(iconDir, { recursive: true });

const esc = (v) => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
function nodeMarkup([tag, attrs]) {
  return `<${tag} ${Object.entries(attrs).filter(([k]) => !k.startsWith("data-detail")).map(([k, v]) => `${k}="${esc(v)}"`).join(" ")}/>`;
}
const OPTICAL_STROKE = { 16: 2.3, 20: 2.15, 24: 2, 32: 1.92, 48: 1.85 };
function nodesFor(icon, variant, size = 24) {
  if (size === 16 && icon.small && icon.small[variant]) return icon.small[variant];
  return icon[variant].filter(([, attrs]) => !(size === 16 && attrs["data-detail"]));
}
function opticalSvg(icon, variant, size = 24) {
  const nodes = nodesFor(icon, variant, size).map(nodeMarkup).join("");
  const rootAttrs = variant === "solid"
    ? 'fill="currentColor" stroke="none"'
    : `fill="none" stroke="currentColor" stroke-width="${OPTICAL_STROKE[size]}" stroke-linecap="round" stroke-linejoin="round"`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" ${rootAttrs} class="nexa-icon" aria-hidden="true">${nodes}</svg>`;
}
function svg(icon, variant, { size = 24, className = "nexa-icon", style = "" } = {}) {
  const nodes = icon[variant].map(nodeMarkup).join("");
  const rootAttrs = variant === "solid"
    ? 'fill="currentColor" stroke="none"'
    : 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" ${rootAttrs} class="${className}"${style ? ` style="${style}"` : ""} aria-hidden="true">${nodes}</svg>`;
}
function writeVariant(icon, variant) {
  const file = path.join(iconDir, `${icon.kebab}-${variant}.svg`);
  fs.writeFileSync(file, svg(icon, variant, { size: 24 }).replace(' class="nexa-icon" aria-hidden="true"', ' aria-hidden="true"') + "\n");
  return file;
}
for (const icon of icons) for (const variant of ["outline", "solid", "duotone"]) writeVariant(icon, variant);

const data = {
  meta: {
    name: "Nexa Icons 2.0 prototype",
    version: "2.0.0-alpha.1",
    grid: 24,
    stroke: 2,
    keyline: 18,
    corner: 2.4,
    icons: icons.length,
    variants: ["outline", "solid", "duotone"],
    sizes: [16, 20, 24, 32, 48],
  },
  icons: icons.map((icon) => ({
    name: icon.name,
    kebab: icon.kebab,
    variants: Object.fromEntries(["outline", "solid", "duotone"].map((v) => [v, svg(icon, v, { size: 24 })] )),
  })),
};
fs.writeFileSync(path.join(OUT, "catalog.json"), JSON.stringify(data, null, 2) + "\n");
fs.writeFileSync(path.join(OUT, "studio-data.js"), `/* generated by design/nexa-2.0/build.mjs */\nwindow.NEXA_V2_DATA = ${JSON.stringify(data)};\n`);

const old = JSON.parse(fs.readFileSync(path.join(ROOT, "data/icons.json"), "utf8"));
const oldByName = new Map(old.icons.map((i) => [i.name, i]));
const oldAlias = { Close: "X" };
const variants = ["outline", "solid", "duotone"];
const sizes = [16, 20, 24, 32, 48];
const iconCell = (icon, variant, size = 48) => `<figure class="cell"><div class="art">${opticalSvg(icon, variant, size)}</div><figcaption>${variant} · ${size}</figcaption></figure>`;
const oldSvg = (name, size = 48) => {
  const item = oldByName.get(oldAlias[name] || name);
  if (!item) return `<span class="missing">missing</span>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${size <= 16 ? 2 : size <= 20 ? 1.75 : 1.5}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${item.inner}</svg>`;
};
const page = (title, body, extraCss = "") => `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${title}</title><style>
:root{color-scheme:light dark;--bg:#fafafa;--surface:#fff;--text:#18181b;--muted:#71717a;--line:#e4e4e7;--accent:#4f46e5}
@media(prefers-color-scheme:dark){:root{--bg:#0c0c0e;--surface:#161618;--text:#f4f4f5;--muted:#a1a1aa;--line:#27272a;--accent:#818cf8}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--text);font:14px/1.5 ui-sans-serif,system-ui,sans-serif}header{padding:28px 32px;border-bottom:1px solid var(--line)}h1{margin:0;font-size:24px;letter-spacing:-.02em}h2{margin:32px 32px 12px;font-size:15px;text-transform:uppercase;letter-spacing:.08em;color:var(--muted)}p{margin:6px 0 0;color:var(--muted)}
table{border-collapse:collapse;width:calc(100% - 64px);margin:0 32px 32px}th,td{border-bottom:1px solid var(--line);padding:10px;text-align:left;vertical-align:middle}th{font-size:11px;text-transform:uppercase;letter-spacing:.06em;color:var(--muted)}td{font-size:13px}.name{font-weight:600}.old,.new{color:var(--text)}.cell{margin:0;text-align:center}.cell .art{display:grid;place-items:center;min-height:64px;padding:8px;border:1px solid var(--line);border-radius:12px;background:var(--surface)}figcaption{font-size:10px;color:var(--muted);margin-top:4px}.variants{display:flex;gap:6px;flex-wrap:wrap}.variants .cell{min-width:74px}.variants .art{min-height:76px}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(160px,1fr));gap:12px;padding:0 32px 32px}.sheet .cell .art{min-height:96px}.missing{color:#dc2626}.dark{background:#0c0c0e;color:#f4f4f5}.dark .cell .art{background:#161618;border-color:#27272a}
${extraCss}</style></head><body>${body}</body></html>`;

const compareRows = icons.map((icon) => `<tr><td class="name">${icon.name}</td><td>${oldSvg(icon.name, 48)}</td><td>${svg(icon, "outline", { size: 48 })}</td><td><div class="variants">${variants.map((v) => `<div class="cell"><div class="art">${svg(icon, v, { size: 32 })}</div><figcaption>${v}</figcaption></div>`).join("")}</div></td><td><div class="variants">${sizes.map((s) => `<div class="cell"><div class="art">${svg(icon, "outline", { size: s })}</div><figcaption>${s}</figcaption></div>`).join("")}</div></td></tr>`).join("\n");
fs.writeFileSync(path.join(OUT, "comparison.html"), page("Nexa 2.0 — old vs new", `<header><h1>Nexa 2.0 — old vs new</h1><p>First 20 icons. Old = Lucide-derived v1 outline; new = Nexa 2.0 outline + solid + duotone, tested at 16/20/24/32/48.</p></header><h2>Side by side</h2><table><thead><tr><th>Icon</th><th>v1 outline</th><th>v2 outline</th><th>v2 variants</th><th>v2 optical sizes</th></tr></thead><tbody>${compareRows}</tbody></table>`));

const sheetSections = icons.map((icon) => `<section><h2>${icon.name}</h2><div class="variants">${variants.flatMap((v) => sizes.map((s) => iconCell(icon, v, s))).join("")}</div></section>`).join("\n");
fs.writeFileSync(path.join(OUT, "contact-sheet.html"), page("Nexa 2.0 — contact sheet", `<header><h1>Nexa 2.0 contact sheet</h1><p>20 representative icons · 3 variants · 5 optical sizes. Validate silhouettes, spacing, and small-size clarity.</p></header>${sheetSections}`));

for (const [src, dst] of [["studio.html", "gallery/v2.html"], ["studio-data.js", "gallery/nexa2.data.js"]]) {
  fs.copyFileSync(path.join(OUT, src), path.join(ROOT, dst));
}
console.log(`Nexa 2.0: ${icons.length} icons × 3 variants, ${icons.length * 6} SVG files, sheets written.`);
