//! The [`IconElement`] GPUI element and the [`icon`] / [`icon_opt`] helpers.

use std::fmt;

use gpui::{
    point, px, size, App, Bounds, Element, ElementId, GlobalElementId, InspectorElementId,
    IntoElement, LayoutId, Refineable, SharedString, Style, StyleRefinement, Styled,
    TransformationMatrix, Window,
};
use nexa_icons::Icon;

use crate::assets::asset_path;

/// Resolves a Nexa icon by canonical name, alias, kebab id or compact form
/// (`"Bell"`, `"bell"`, `"XIcon"`, `"Triangle Alert"`, `"RotateCcwClock"`, …).
///
/// Returns `None` for unknown names.
pub fn resolve_icon(name: &str) -> Option<&'static Icon> {
    nexa_icons::get(name)
}

/// Creates an icon element for use inside a GPUI view.
///
/// The name goes through the full Nexa lookup (canonical name, alias, kebab id,
/// case-insensitive, separator-insensitive), so `"bell"`, `"Bell"`, `"XIcon"`
/// and `"Triangle Alert"` all work. Unknown names render nothing; use
/// [`icon_opt`] to detect that case up front.
///
/// The element defaults to 24×24px and inherits the surrounding text color, just
/// like a `currentColor` SVG on the web. Size it with the normal GPUI style
/// helpers ([`Styled::size`], [`Styled::w`], [`Styled::h`]) and color it with
/// [`Styled::text_color`] (or an ancestor's `text_color`).
///
/// ```
/// # use gpui::{div, px, rgb, prelude::*};
/// # use nexa_icons_gpui::icon;
/// let row = div()
///     .flex()
///     .gap_2()
///     .text_color(rgb(0x27272a))
///     .child(icon("bell"))
///     .child(icon("Bell").size(px(20.0)));
/// # let _ = row;
/// ```
///
/// Rendered icons are decorative by design (the SVG is `aria-hidden`), which
/// matches GPUI's current accessibility model; pair the icon with a text label
/// or a tooltip at the call site.
#[track_caller]
pub fn icon(name: impl AsRef<str>) -> IconElement {
    IconElement::new(name.as_ref())
}

/// Like [`icon`], but returns `None` when `name` does not resolve to an icon.
///
/// Useful for dynamic names (e.g. search results, user configuration) where an
/// unknown icon should be skipped rather than rendered as an empty box.
///
/// ```
/// # use nexa_icons_gpui::icon_opt;
/// assert!(icon_opt("bell").is_some());
/// assert!(icon_opt("not-a-real-icon").is_none());
/// ```
pub fn icon_opt(name: impl AsRef<str>) -> Option<IconElement> {
    if nexa_icons::get(name.as_ref()).is_some() {
        Some(IconElement::new(name.as_ref()))
    } else {
        None
    }
}

/// A GPUI element that paints one Nexa icon.
///
/// Build it with [`icon`]; style it with the usual GPUI styling API because it
/// implements [`gpui::Styled`]. Painting goes through GPUI's own monochrome SVG
/// renderer (`Window::paint_svg`) using in-memory bytes generated by the
/// `nexa-icons` crate — no asset files, no network, no image decoding.
///
/// The stroke width follows the Nexa size rule from the element's *rendered*
/// bounds (16px => 2, 20px => 1.75, 24px+ => 1.5, in 24-grid units), so resizing
/// an icon keeps its optical weight correct. Override it with
/// [`IconElement::stroke_width`] when a design calls for a specific weight.
#[derive(Clone, Debug)]
pub struct IconElement {
    kebab: Option<&'static str>,
    stroke_width: Option<f32>,
    style: StyleRefinement,
}

impl IconElement {
    fn new(name: &str) -> Self {
        let mut style = StyleRefinement::default();
        // Default Nexa "lg" size: 24px. `Styled::size` replaces this when the
        // caller sets an explicit size.
        style.size.width = Some(px(24.0).into());
        style.size.height = Some(px(24.0).into());
        Self {
            kebab: nexa_icons::get(name).map(|icon| icon.kebab),
            stroke_width: None,
            style,
        }
    }

    /// Whether the requested name resolved to a catalogue icon.
    pub fn is_valid(&self) -> bool {
        self.kebab.is_some()
    }

    /// The resolved kebab id, e.g. `Some("bell")`.
    pub fn kebab(&self) -> Option<&'static str> {
        self.kebab
    }

    /// Overrides the stroke width (in 24-grid units) instead of deriving it from
    /// the rendered size. Invalid values (zero, negative, NaN) are ignored.
    ///
    /// ```
    /// # use gpui::{px, prelude::*};
    /// # use nexa_icons_gpui::icon;
    /// let heavy = icon("bell").size(px(20.0)).stroke_width(2.0);
    /// # let _ = heavy;
    /// ```
    pub fn stroke_width(mut self, width: f32) -> Self {
        if width.is_finite() && width > 0.0 {
            self.stroke_width = Some(width);
        }
        self
    }
}

impl fmt::Display for IconElement {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            formatter,
            "IconElement({})",
            self.kebab.unwrap_or("<unknown icon>")
        )
    }
}

impl IntoElement for IconElement {
    type Element = Self;

    fn into_element(self) -> Self::Element {
        self
    }
}

impl Styled for IconElement {
    fn style(&mut self) -> &mut StyleRefinement {
        &mut self.style
    }
}

impl Element for IconElement {
    type RequestLayoutState = Style;
    type PrepaintState = ();

    fn id(&self) -> Option<ElementId> {
        None
    }

    fn source_location(&self) -> Option<&'static std::panic::Location<'static>> {
        None
    }

    fn request_layout(
        &mut self,
        _id: Option<&GlobalElementId>,
        _inspector_id: Option<&InspectorElementId>,
        window: &mut Window,
        cx: &mut App,
    ) -> (LayoutId, Self::RequestLayoutState) {
        let mut style = Style::default();
        style.refine(&self.style);
        let layout_id = window.request_layout(style.clone(), [], cx);
        (layout_id, style)
    }

    fn prepaint(
        &mut self,
        _id: Option<&GlobalElementId>,
        _inspector_id: Option<&InspectorElementId>,
        _bounds: Bounds<gpui::Pixels>,
        _request_layout: &mut Self::RequestLayoutState,
        _window: &mut Window,
        _cx: &mut App,
    ) -> Self::PrepaintState {
    }

    fn paint(
        &mut self,
        _id: Option<&GlobalElementId>,
        _inspector_id: Option<&InspectorElementId>,
        bounds: Bounds<gpui::Pixels>,
        style: &mut Style,
        _prepaint: &mut Self::PrepaintState,
        window: &mut Window,
        cx: &mut App,
    ) {
        let kebab = self.kebab;
        let stroke_width = self.stroke_width;

        // Resolve the color the way `currentColor` works on the web: the
        // element's own `text_color` wins, otherwise the inherited text style.
        let mut color = style
            .text
            .color
            .unwrap_or_else(|| window.text_style().color);
        if let Some(opacity) = style.opacity {
            color.a = (color.a * opacity).clamp(0.0, 1.0);
        }

        style.paint(bounds, window, cx, move |window, cx| {
            let Some(kebab) = kebab else {
                return;
            };

            let width = f32::from(bounds.size.width);
            let height = f32::from(bounds.size.height);
            let side = width.min(height);
            if !side.is_finite() || side < 1.0 {
                return;
            }

            // Icons are square: paint a centred square inside non-square bounds.
            let square = Bounds {
                origin: bounds.origin + point(px((width - side) / 2.0), px((height - side) / 2.0)),
                size: size(px(side), px(side)),
            };

            let size_px = side.round().clamp(1.0, 4096.0) as u32;
            let path = asset_path(kebab, size_px, stroke_width);
            window
                .paint_svg(
                    square,
                    SharedString::from(path),
                    TransformationMatrix::unit(),
                    color,
                    cx,
                )
                .ok();
        });
    }
}
