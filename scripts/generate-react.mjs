#!/usr/bin/env node
/**
 * T2 — generate the React/TypeScript package from data/icons.json.
 *
 * Emits:
 *   src/icons/<kebab>.tsx   one pure-annotated component per icon (tree-shakeable)
 *   src/registry.ts         kebab-keyed data + O(1) name lookup for the generic <Icon>
 *   src/map.ts              the fixed Nexa concept -> icon map
 *   src/index.ts            barrel: 166 components + aliases + types
 *
 * The generated components are static: no fetch, no runtime lookup, no deps
 * beyond react. Importing one icon ships one icon.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const data = JSON.parse(fs.readFileSync(path.join(ROOT, "data/icons.json"), "utf8"));
const icons = data.icons;
const out = path.join(ROOT, "src");
const iconDir = path.join(out, "icons");
fs.mkdirSync(iconDir, { recursive: true });

const HEADER = `/* Generated by scripts/generate-react.mjs from data/icons.json — do not edit. */\n`;
const q = JSON.stringify;

// ---------------------------------------------------------------------------
// 1. One component module per icon.
// ---------------------------------------------------------------------------
const expectedModules = new Set(icons.map((icon) => `${icon.kebab}.tsx`));
for (const file of fs.readdirSync(iconDir)) {
  if (file.endsWith(".tsx") && !expectedModules.has(file)) {
    fs.rmSync(path.join(iconDir, file), { force: true });
  }
}
for (const icon of icons) {
  const file = `${HEADER}import { createIcon } from "../createIcon.js";

export const ${icon.name} = /*#__PURE__*/ createIcon({
  name: ${q(icon.name)},
  kebab: ${q(icon.kebab)},
  fillSafe: ${icon.fillSafe ? "true" : "false"},
  preset: ${q(icon.anim.preset)},
  trigger: ${q(icon.anim.trigger)},
  nodes: ${q(icon.nodes).replace(/"([a-zA-Z-]+)":/g, "$1:")},
});
`;
  fs.writeFileSync(path.join(iconDir, `${icon.kebab}.tsx`), file);
}

// ---------------------------------------------------------------------------
// 2. Registry for the generic <Icon name="..."> (falls back to runtime data).
// ---------------------------------------------------------------------------
const compact = (s) => s.toLowerCase().replace(/[\s_-]+/g, "");
const lookup = new Map();
for (const icon of icons) {
  const kebab = icon.kebab;
  const keys = new Set([
    kebab,
    compact(kebab),
    icon.name.toLowerCase(),
    compact(icon.name),
  ]);
  for (const alias of icon.aliases) {
    keys.add(alias.toLowerCase());
    keys.add(compact(alias));
  }
  for (const key of keys) lookup.set(key, kebab);
}
const registryEntries = icons
  .map(
    (i) => `  ${q(i.kebab)}: { name: ${q(i.name)}, kebab: ${q(i.kebab)}, fillSafe: ${i.fillSafe ? "true" : "false"}, preset: ${q(i.anim.preset)}, trigger: ${q(i.anim.trigger)}, nodes: ${q(i.nodes).replace(/"([a-zA-Z-]+)":/g, "$1:")} },`
  )
  .join("\n");
const lookupEntries = [...lookup.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => `  ${q(k)}: ${q(v)},`)
  .join("\n");

fs.writeFileSync(
  path.join(out, "registry.ts"),
  `${HEADER}import type { NexaIconData } from "./types.js";

export const REGISTRY: Record<string, NexaIconData> = {
${registryEntries}
};

/** Normalized name -> kebab id. Accepts PascalCase, kebab-case, aliases (XIcon, TriangleAlert). */
export const LOOKUP: Record<string, string> = {
${lookupEntries}
};

export const ICON_NAMES: readonly string[] = ${q(icons.map((i) => i.name))};

export function resolveKebab(input: string): string | undefined {
  const raw = String(input ?? "").trim();
  if (!raw) return undefined;
  return LOOKUP[raw.toLowerCase()] ?? LOOKUP[raw.toLowerCase().replace(/[\\s_-]+/g, "")];
}
`
);

// ---------------------------------------------------------------------------
// 2b. Semantic swap pairs (data/swaps.json) -> src/swaps.ts
//     Reverse entries are generated unless an explicit reverse exists.
// ---------------------------------------------------------------------------
const swapSource = JSON.parse(fs.readFileSync(path.join(ROOT, "data/swaps.json"), "utf8"));
const byName = new Map(icons.map((icon) => [icon.name, icon]));
const SWAP = {};
const SWAP_PAIRS = [];
const SWAP_MODES = new Set(["mirror", "flip", "rotate", "slide", "fade"]);
const addSwap = (fromName, toName, mode, onlyIfMissing) => {
  const from = byName.get(fromName);
  const to = byName.get(toName);
  if (!from) throw new Error(`swaps.json: unknown icon "${fromName}"`);
  if (!to) throw new Error(`swaps.json: unknown icon "${toName}"`);
  if (!SWAP_MODES.has(mode)) throw new Error(`swaps.json: bad mode "${mode}"`);
  const entry = { to: to.name, mode };
  let added = 0;
  for (const key of [compact(from.name), compact(from.kebab)]) {
    if (onlyIfMissing && key in SWAP) continue;
    SWAP[key] = entry;
    added += 1;
  }
  if (added > 0) SWAP_PAIRS.push([from.name, to.name, mode]);
};
for (const [a, b, mode] of swapSource.pairs) {
  addSwap(a, b, mode, false);
  addSwap(b, a, mode, true);
}
// Aliases share the canonical icon's pair (XIcon behaves exactly like X).
for (const icon of icons) {
  const entry = SWAP[compact(icon.name)];
  if (!entry) continue;
  for (const alias of icon.aliases) SWAP[compact(alias)] = entry;
}

fs.writeFileSync(
  path.join(out, "swaps.ts"),
  `${HEADER}export type SwapMode = "mirror" | "flip" | "rotate" | "slide" | "fade";

/** Directed swap edges as [from, to, mode]; implicit reverses are added unless that source already has a pair. */
export const SWAP_PAIRS: readonly (readonly [string, string, SwapMode])[] = ${JSON.stringify(SWAP_PAIRS)};

/** Compact display name -> counterpart + transition mode. */
export const SWAP: Record<string, { readonly to: string; readonly mode: SwapMode }> = ${JSON.stringify(SWAP)};

const compact = (value: string): string => String(value).toLowerCase().replace(/[\\s_-]+/g, "");

/** Semantic counterpart for a click toggle, e.g. swapTarget("ArrowLeft") => "ArrowRight". */
export function swapTarget(name: string): string | undefined {
  return SWAP[compact(name)]?.to;
}

/** Transition mode for an icon's semantic pair (falls back to "fade"). */
export function swapModeFor(name: string): SwapMode {
  return SWAP[compact(name)]?.mode ?? "fade";
}
`
);

// ---------------------------------------------------------------------------
// 3. Concept map + barrel.
// ---------------------------------------------------------------------------
fs.writeFileSync(
  path.join(out, "map.ts"),
  `${HEADER}import type { NexaIconName } from "./types.js";

/** Nexa concept -> icon (from data/icons.json meta.nexaMap). Keep this map fixed. */
export const NEXA_MAP = {
${Object.entries(data.meta.nexaMap)
  .map(([concept, name]) => `  ${concept}: ${q(name)},`)
  .join("\n")}
} as const satisfies Record<string, NexaIconName>;
`
);

// Category barrels: `import { Bell } from "@nexa/icons/communication"`.
const categories = data.meta.categories ?? [];
const categoryDir = path.join(out, "categories");
if (categories.length) fs.mkdirSync(categoryDir, { recursive: true });
const byDisplay = new Map(icons.map((i) => [i.name, i]));
const expectedCategoryFiles = new Set(categories.map((c) => `${c.id}.ts`));
for (const file of fs.existsSync(categoryDir) ? fs.readdirSync(categoryDir) : []) {
  if (file.endsWith(".ts") && !expectedCategoryFiles.has(file) && !["index.ts","catalog.ts"].includes(file)) {
    fs.rmSync(path.join(categoryDir, file), { force: true });
  }
}
for (const category of categories) {
  const entries = category.icons
    .map((name) => byDisplay.get(name))
    .filter(Boolean)
    .map((icon) => `export { ${icon.name} } from "../icons/${icon.kebab}.js";`);
  fs.writeFileSync(
    path.join(categoryDir, `${category.id}.ts`),
    `${HEADER}${entries.join("\n")}\n`
  );
}
if (categories.length) {
  const manifest = categories.map((c) => ({
    id: c.id,
    label: c.label,
    description: c.description,
    icons: c.icons.filter((n) => byDisplay.has(n)),
  }));
  fs.writeFileSync(
    path.join(categoryDir, "catalog.ts"),
    `${HEADER}export interface NexaCategory { readonly id: string; readonly label: string; readonly description: string; readonly icons: readonly string[]; }\n\nexport const CATEGORIES: readonly NexaCategory[] = ${JSON.stringify(manifest, null, 2)};\n`
  );
}

const exports = icons.map((i) => `export { ${i.name} } from "./icons/${i.kebab}.js";`);
const aliasExports = icons
  .filter((i) => i.aliases.length > 1)
  .flatMap((i) =>
    i.aliases
      .filter((a) => a !== i.name)
      .map((alias) => `export { ${i.name} as ${alias} } from "./icons/${i.kebab}.js";`)
  );

fs.writeFileSync(
  path.join(out, "index.ts"),
  `${HEADER}/* Types */
export type { NexaIconName, NexaIconProps, NexaIconData, NexaPreset, NexaSize, NexaTrigger, NexaShape, NexaFill, Nexa3D, NexaGlass, NexaGradient, NexaGlassAnim } from "./types.js";
export type { NexaIconComponent } from "./types.js";

/* Runtime helpers */
export { createIcon, strokeForSize, STROKE_FOR_PX, SIZE_PX, PRESETS } from "./createIcon.js";
export { Icon, getIcon } from "./Icon.js";
export { IconSwap, IconToggle } from "./Swap.js";
export type { IconSwapProps, IconToggleProps } from "./Swap.js";
export { SWAP, SWAP_PAIRS, swapTarget, swapModeFor } from "./swaps.js";
export type { SwapMode } from "./swaps.js";
export { NEXA_MAP } from "./map.js";
${categories.length ? `export { CATEGORIES } from "./categories/catalog.js";\nexport type { NexaCategory } from "./categories/catalog.js";` : ""}
export { ICON_NAMES, resolveKebab } from "./registry.js";

/* ${icons.length} icons */
${exports.join("\n")}

/* Duplicate requested names kept as aliases: XIcon === X, TriangleAlert === AlertTriangle */
${aliasExports.join("\n")}
`
);

// ---------------------------------------------------------------------------
// 4. NexaIconName union (generated for prop safety, zero runtime cost).
// ---------------------------------------------------------------------------
const iconNameUnion = icons
  .flatMap((i) => [q(i.name), ...i.aliases.filter((a) => a !== i.name).map((a) => q(a))])
  .join(" | ");
const typesPath = path.join(out, "types.ts");
if (!fs.existsSync(typesPath)) {
  console.error("src/types.ts is missing — run from the repo root.");
  process.exit(1);
}
const typesSource = fs.readFileSync(typesPath, "utf8");
const unionRegex = /\/\* ICON_NAME_UNION_START \*\/[\s\S]*?\/\* ICON_NAME_UNION_END \*\//;
if (unionRegex.test(typesSource)) {
  fs.writeFileSync(
    typesPath,
    typesSource.replace(
      unionRegex,
      `/* ICON_NAME_UNION_START */\nexport type NexaIconName = ${iconNameUnion};\n/* ICON_NAME_UNION_END */`
    )
  );
} else {
  console.warn("icon-name union markers missing from src/types.ts");
}

console.log(`generated ${icons.length} icon modules + registry + barrel in src/`);
console.log(`lookup keys: ${lookup.size}, aliases exported: ${aliasExports.length}`);
